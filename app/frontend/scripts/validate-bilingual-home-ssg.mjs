import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { load } from 'cheerio';
const read = (paths) => {
  const file = paths.map(p => path.join(process.cwd(), 'dist', p)).find(p => fs.existsSync(p));
  assert.ok(file, 'Missing prerendered homepage: ' + paths.join(', '));
  return load(fs.readFileSync(file, 'utf8'));
};
const en = read(['index.html']), ar = read(['ar.html','ar/index.html']);
const enHome = en('[data-home-locale="en"]'), arHome = ar('[data-home-locale="ar"]');
assert.equal(enHome.length,1); assert.equal(arHome.length,1);
assert.equal(arHome.attr('lang'),'ar-KW'); assert.equal(arHome.attr('dir'),'rtl');
assert.equal(enHome.find('h1').length,1); assert.equal(arHome.find('h1').length,1);
assert.equal(arHome.find('section').length,enHome.find('section').length);
assert.equal(arHome.find('img').length,enHome.find('img').length);
assert.ok(arHome.find('img[fetchpriority="high"]').length === 1);
assert.ok(arHome.find('a[href="/ar/book"]').length >= 3);
assert.equal(arHome.find('a[href="/book"]').length,0);
assert.equal(arHome.find('#homepage-services-grid a').length,6);
assert.equal(arHome.find('article').length,enHome.find('article').length);
for (const dest of ['/ar/laptop-battery-replacement-kuwait','/ar/computer-repair-mangaf','/ar/computer-repair-ahmadi']) assert.ok(arHome.find('a[href="'+dest+'"]').length > 0,dest);
assert.equal(arHome.find('[id^="homepage-faq-question-"]').length,7);
assert.equal(arHome.find('[id^="homepage-faq-answer-faq-ar-home-"]').length,7);
for (const phrase of ['تصليح وصيانة الكمبيوتر واللابتوب','أسعار التصليح بكل وضوح','قول لنا شنو المشكلة بجهازك','شوف تقييمات عملائنا على Google']) assert.ok(arHome.text().includes(phrase),phrase);
assert.equal(ar('link[rel="canonical"]').attr('href'),'https://www.computerrepairkuwait.com/ar');
assert.equal(en('link[rel="canonical"]').attr('href'),'https://www.computerrepairkuwait.com/');
assert.ok(ar('link[hreflang="en-KW"]').length); assert.ok(en('link[hreflang="ar-KW"]').length);
console.log('Bilingual homepage SSG parity passed: shared layout, photography, booking, services, FAQs and canonical/hreflang.');
